using System.Globalization;
using Mono.Cecil;

namespace StubGen;

internal static class Emitter
{
    public static void Write(TextWriter writer, string assemblyName, List<TypeUsage> topLevel,
        Dictionary<string, TypeUsage> all)
    {
        writer.WriteLine("// <auto-generated>");
        writer.WriteLine($"// Compile-only declaration stubs for {assemblyName}.");
        writer.WriteLine("// Generated by ci/stubgen from the members this plugin links against: no game code, only the API shape.");
        writer.WriteLine("// Regenerate after adding calls to new game APIs (see ci/README.md).");
        writer.WriteLine("// </auto-generated>");
        writer.WriteLine("#pragma warning disable CS0067, CS0108, CS0114, CS0169, CS0649, CS1591");
        writer.WriteLine();

        foreach (var group in topLevel.GroupBy(t => t.Definition.Namespace).OrderBy(g => g.Key, StringComparer.Ordinal))
        {
            var hasNamespace = !string.IsNullOrEmpty(group.Key);
            if (hasNamespace)
            {
                writer.WriteLine($"namespace {group.Key}");
                writer.WriteLine("{");
            }

            foreach (var usage in group)
            {
                WriteType(writer, usage, all, hasNamespace ? 1 : 0);
                writer.WriteLine();
            }

            if (hasNamespace)
            {
                writer.WriteLine("}");
                writer.WriteLine();
            }
        }
    }

    private static void WriteType(TextWriter writer, TypeUsage usage, Dictionary<string, TypeUsage> all, int indent)
    {
        var definition = usage.Definition;
        var pad = new string(' ', indent * 4);

        if (definition.IsEnum)
        {
            var underlying = definition.Fields.FirstOrDefault(f => f.Name == "value__")?.FieldType;
            var underlyingText = underlying == null || underlying.FullName == "System.Int32"
                ? string.Empty
                : " : " + TypeName(underlying);
            writer.WriteLine($"{pad}public enum {CleanName(definition.Name)}{underlyingText}");
            writer.WriteLine($"{pad}{{");
            foreach (var field in definition.Fields.Where(f => f.HasConstant))
            {
                writer.WriteLine($"{pad}    {field.Name} = {Convert.ToString(field.Constant, CultureInfo.InvariantCulture)},");
            }

            writer.WriteLine($"{pad}}}");
            return;
        }

        if (IsDelegate(definition))
        {
            var invoke = definition.Methods.FirstOrDefault(m => m.Name == "Invoke");
            if (invoke != null)
            {
                writer.WriteLine($"{pad}public delegate {TypeName(invoke.ReturnType)} {CleanName(definition.Name)}({Parameters(invoke)});");
            }

            return;
        }

        if (definition.IsInterface)
        {
            writer.WriteLine($"{pad}public interface {definition.Name} {{ }}");
            return;
        }

        var isStatic = definition.IsAbstract && definition.IsSealed;
        var keyword = definition.IsValueType ? "struct" : "class";
        var modifiers = isStatic ? "public static" : "public";

        var baseType = BaseTypeName(definition);
        var typeParameters = definition.HasGenericParameters
            ? "<" + string.Join(", ", definition.GenericParameters.Select(p => p.Name)) + ">"
            : string.Empty;
        var header = $"{pad}{modifiers} {keyword} {CleanName(definition.Name)}{typeParameters}{baseType}";
        writer.WriteLine(header);
        writer.WriteLine($"{pad}{{");

        foreach (var fieldName in usage.Fields.OrderBy(x => x, StringComparer.Ordinal))
        {
            var field = definition.Fields.FirstOrDefault(f => f.Name == fieldName);
            if (field == null)
            {
                continue;
            }

            var staticText = field.IsStatic ? "static " : string.Empty;
            writer.WriteLine($"{pad}    {Visibility(field)} {staticText}{TypeName(field.FieldType)} {field.Name};");
        }

        foreach (var propertyUsage in usage.Properties.Values.OrderBy(p => p.Property.Name, StringComparer.Ordinal))
        {
            var property = propertyUsage.Property;
            if (!propertyUsage.Get && !propertyUsage.Set)
            {
                continue;
            }

            // Write-only properties need an explicit accessor body: an auto property has to have a getter.
            var accessors = propertyUsage.Get && propertyUsage.Set
                ? "{ get { return default; } set { } }"
                : propertyUsage.Get
                    ? "{ get { return default; } }"
                    : "{ set { } }";

            var staticText = (property.GetMethod ?? property.SetMethod)?.IsStatic == true ? "static " : string.Empty;
            var visibility = Visibility(property.GetMethod ?? property.SetMethod);
            writer.WriteLine($"{pad}    {visibility} {staticText}{TypeName(property.PropertyType)} {property.Name} {accessors}");
        }

        foreach (var method in usage.Methods.Values.OrderBy(m => m.Name, StringComparer.Ordinal)
                     .ThenBy(m => m.Parameters.Count))
        {
            WriteMethod(writer, method, definition, pad + "    ");
        }

        foreach (var constructorFullName in usage.Constructors)
        {
            var constructor = definition.Methods.FirstOrDefault(m => m.FullName == constructorFullName);
            if (constructor != null)
            {
                writer.WriteLine($"{pad}    {Visibility(constructor)} {CleanName(definition.Name)}({Parameters(constructor)}) {{ }}");
            }
        }

        foreach (var nested in all.Values.Where(t => t.Definition.DeclaringType?.FullName == definition.FullName)
                     .OrderBy(t => t.Definition.Name, StringComparer.Ordinal))
        {
            WriteType(writer, nested, all, indent + 1);
            writer.WriteLine();
        }

        writer.WriteLine($"{pad}}}");
    }

    private static void WriteMethod(TextWriter writer, MethodDefinition method, TypeDefinition owner, string pad)
    {
        var generic = method.HasGenericParameters
            ? "<" + string.Join(", ", method.GenericParameters.Select(p => p.Name)) + ">"
            : string.Empty;
        var staticText = method.IsStatic ? "static " : string.Empty;
        var returnType = TypeName(method.ReturnType);
        var body = returnType == "void" ? "{ }" : "{ return default; }";
        var name = method.Name;

        writer.WriteLine($"{pad}{Visibility(method)} {staticText}{returnType} {name}{generic}({Parameters(method)}) {body}");
    }

    /// <summary>
    ///     Keeps the real accessibility, so the stub build fails to compile when the plugin starts reading a member that
    ///     is not public in the game assembly - exactly the mistake that only blows up on a player's runtime.
    ///     Types stay public: they are only declaration carriers here.
    /// </summary>
    private static string Visibility(MethodDefinition? method)
    {
        if (method == null || method.IsPublic) return "public";
        if (method.IsFamilyOrAssembly) return "protected internal";
        if (method.IsFamily) return "protected";
        if (method.IsFamilyAndAssembly) return "private protected";
        if (method.IsAssembly) return "internal";
        return "private";
    }

    private static string Visibility(FieldDefinition field)
    {
        if (field.IsPublic) return "public";
        if (field.IsFamilyOrAssembly) return "protected internal";
        if (field.IsFamily) return "protected";
        if (field.IsFamilyAndAssembly) return "private protected";
        if (field.IsAssembly) return "internal";
        return "private";
    }

    private static string Parameters(MethodDefinition method)
    {
        var parameters = new List<string>();
        var isExtension = method.CustomAttributes.Any(a =>
            a.AttributeType.FullName == "System.Runtime.CompilerServices.ExtensionAttribute");

        for (var i = 0; i < method.Parameters.Count; i++)
        {
            var parameter = method.Parameters[i];
            var byReference = parameter.ParameterType as ByReferenceType;
            var prefix = string.Empty;

            if (byReference != null)
            {
                prefix = parameter.IsOut ? "out " : parameter.IsIn ? "in " : "ref ";
            }
            else if (parameter.CustomAttributes.Any(a => a.AttributeType.FullName == "System.ParamArrayAttribute"))
            {
                prefix = "params ";
            }
            else if (isExtension && i == 0)
            {
                prefix = "this ";
            }

            var type = TypeName(byReference?.ElementType ?? parameter.ParameterType);
            var defaultText = parameter.HasDefault ? " = " + DefaultLiteral(parameter) : string.Empty;
            parameters.Add($"{prefix}{type} {parameter.Name}{defaultText}");
        }

        return string.Join(", ", parameters);
    }

    private static string DefaultLiteral(ParameterDefinition parameter)
    {
        var constant = parameter.Constant;
        if (constant == null)
        {
            return "default";
        }

        return constant switch
        {
            bool value => value ? "true" : "false",
            string value => "\"" + value.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"",
            char value => "'" + (value == '\'' ? "\\'" : value.ToString()) + "'",
            float value => value.ToString("R", CultureInfo.InvariantCulture) + "f",
            double value => value.ToString("R", CultureInfo.InvariantCulture),
            decimal value => value.ToString(CultureInfo.InvariantCulture) + "m",
            long value => value.ToString(CultureInfo.InvariantCulture),
            ulong value => value.ToString(CultureInfo.InvariantCulture),
            _ => "default"
        };
    }

    private static string BaseTypeName(TypeDefinition definition)
    {
        var baseType = definition.BaseType;
        if (baseType == null)
        {
            return string.Empty;
        }

        var fullName = baseType.FullName;
        if (fullName is "System.Object" or "System.ValueType" or "System.Enum" or "System.MulticastDelegate")
        {
            return string.Empty;
        }

        return " : " + TypeName(baseType);
    }

    private static bool IsDelegate(TypeDefinition definition)
    {
        return definition.BaseType?.FullName == "System.MulticastDelegate";
    }

    private static string CleanName(string name)
    {
        var arity = name.IndexOf('`');
        return arity >= 0 ? name.Substring(0, arity) : name;
    }

    private static string TypeName(TypeReference reference, bool includeTypeParameters = true)
    {
        switch (reference)
        {
            case GenericParameter genericParameter:
                return genericParameter.Name;
            case ArrayType array:
                return TypeName(array.ElementType) + "[" + new string(',', array.Rank - 1) + "]";
            case ByReferenceType byReference:
                return TypeName(byReference.ElementType);
            case PointerType pointer:
                return TypeName(pointer.ElementType) + "*";
            case GenericInstanceType genericInstance:
                return TypeName(genericInstance.ElementType, includeTypeParameters: false) + "<" +
                       string.Join(", ", genericInstance.GenericArguments.Select(a => TypeName(a))) + ">";
            case OptionalModifierType optionalModifier:
                return TypeName(optionalModifier.ElementType);
            case RequiredModifierType requiredModifier:
                return TypeName(requiredModifier.ElementType);
            case TypeSpecification specification:
                return TypeName(specification.ElementType);
        }

        var name = reference.Name;
        var arity = name.IndexOf('`');
        if (arity >= 0)
        {
            name = name.Substring(0, arity);
        }

        var prefix = reference.DeclaringType != null
            ? TypeName(reference.DeclaringType, includeTypeParameters) + "."
            : string.IsNullOrEmpty(reference.Namespace)
                ? "global::"
                : "global::" + reference.Namespace + ".";

        var typeParameters = includeTypeParameters && reference.HasGenericParameters
            ? "<" + string.Join(", ", reference.GenericParameters.Select(p => p.Name)) + ">"
            : string.Empty;

        var full = prefix + name + typeParameters;

        return full == "global::System.Void" ? "void" : full;
    }
}
